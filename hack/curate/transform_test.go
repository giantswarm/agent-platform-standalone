func TestTransformUmbrellaKey(t *testing.T) {
	t.Run("must come from the overlay", func(t *testing.T) {
		in := fixtureInputs(t)
		in.Contract = parseDocument(t, strings.Replace(fixtureContract, "gatewayApi:\n  gateway:\n    create: false\n", "", 1))
		_, err := Transform(in)
		require.ErrorContains(t, err, "keys.gatewayApi: action umbrella, but neither overlay defines it")
	})
	t.Run("fleet must not define it", func(t *testing.T) {
		in := fixtureInputs(t)
		in.Fleet = parseDocument(t, fixtureFleet+"gatewayApi:\n  gateway: {}\n")
		_, err := Transform(in)
		require.ErrorContains(t, err, `fleet key "gatewayApi" is declared umbrella-only`)
	})
	t.Run("connectivity must not define it", func(t *testing.T) {
		in := fixtureInputs(t)
		in.Connectivity = parseDocument(t, fixtureConnectivity+"gatewayApi:\n  gateway: {}\n")
		_, err := Transform(in)
		require.ErrorContains(t, err, `connectivity key "gatewayApi" is declared umbrella-only`)
	})
}

