func TestConfigValidateMoveTo(t *testing.T) {
	var config Config
	require.NoError(t, yaml.Unmarshal([]byte(strings.Replace(fixtureConfig,
		"ingress: {action: wiring, allowShadow: true}", "ingress: {action: wiring, allowShadow: true, moveTo: flat}", 1)), &config))
	require.ErrorContains(t, config.Validate(), "keys.ingress: moveTo \"flat\" must be a dotted path")

	config = Config{}
	require.NoError(t, yaml.Unmarshal([]byte(strings.Replace(fixtureConfig,
		"global: {action: keep, allowShadow: true}", "global: {action: keep, allowShadow: true, moveTo: a.b}", 1)), &config))
	require.ErrorContains(t, config.Validate(), "keys.global: moveTo is only valid with action wiring")

	// A dependency block is placed after the relocation and would replace it.
	config = Config{}
	require.NoError(t, yaml.Unmarshal([]byte(strings.Replace(fixtureConfig,
		"moveTo: global.networkPolicy", "moveTo: muster.networkPolicy", 1)), &config))
	require.ErrorContains(t, config.Validate(), `keys.networkPolicy: moveTo "muster.networkPolicy" starts at dependency "muster"`)

	config = Config{}
	require.NoError(t, yaml.Unmarshal([]byte(strings.Replace(fixtureConfig,
		"moveTo: global.networkPolicy", "moveTo: gitops.networkPolicy", 1)), &config))
	require.ErrorContains(t, config.Validate(), `keys.networkPolicy: moveTo "gitops.networkPolicy" must start at an umbrella-owned top-level key`)
}

