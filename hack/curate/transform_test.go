func TestTransformOverlay(t *testing.T) {
	t.Run("unknown top-level key", func(t *testing.T) {
		in := fixtureInputs(t)
		in.Overlay = parseDocument(t, fixtureOverlay+"policyEngine: none\n")
		_, err := Transform(in)
		require.ErrorContains(t, err, `overlay key "policyEngine"`)
	})
	t.Run("unknown components entry", func(t *testing.T) {
		in := fixtureInputs(t)
		in.Overlay = parseDocument(t, fixtureOverlay+"components:\n  nope:\n    enabled: true\n")
		_, err := Transform(in)
		require.ErrorContains(t, err, "overlay components.nope is not a dependency")
	})
	t.Run("applied last", func(t *testing.T) {
		in := fixtureInputs(t)
		in.Overlay = parseDocument(t, fixtureOverlay+"components:\n  kagent:\n    enabled: true\ningress:\n  parentRefs:\n    - name: edge\n")
		result, err := Transform(in)
		require.NoError(t, err)
		values := decodeValues(t, result.Document)
		require.Equal(t, true, asMap(t, asMap(t, values["components"])["kagent"])["enabled"])
		require.Contains(t, asMap(t, asMap(t, values["components"])["kagent"]), "controllerRoute", "overlay merges, it does not replace")
		require.Equal(t, 1, asMap(t, values["muster"])["replicaCount"])
		require.Equal(t, "muster", asMap(t, values["muster"])["fullnameOverride"])
		require.Len(t, asMap(t, values["ingress"])["parentRefs"], 1, "sequences are replaced")
	})
}

// The vanilla overlay only flips defaults the fleet-derived values (contract
// included) already carry: a fleet rename must orphan the override loudly, not
// silently turn the default back on. Dependency blocks are exempt — they are
// forwarded to component charts whose own defaults the generator cannot see.
func TestTransformVanillaOverlayMustFlipExistingPaths(t *testing.T) {
	in := fixtureInputs(t)
	in.Overlay = parseDocument(t, fixtureOverlay+"ingress:\n  renamedKey: true\n")
	_, err := Transform(in)
	require.ErrorContains(t, err, `overlay path "ingress.renamedKey" does not exist`)

	in = fixtureInputs(t)
	in.Overlay = parseDocument(t, fixtureOverlay+"components:\n  kagent:\n    ghostWiring: true\n")
	_, err = Transform(in)
	require.ErrorContains(t, err, `overlay path "components.kagent.ghostWiring" does not exist`)

	in = fixtureInputs(t)
	in.Overlay = parseDocument(t, fixtureOverlay+"agent-platform-mcps:\n  chartOwnDefault: false\n")
	_, err = Transform(in)
	require.NoError(t, err, "a dependency block flips component-chart defaults the generator cannot see")
}

