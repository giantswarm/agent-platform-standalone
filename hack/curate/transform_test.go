func TestTransformShape(t *testing.T) {
	result, err := Transform(fixtureInputs(t))
	require.NoError(t, err)
	document, components := result.Document, result.Components
	require.Len(t, components, 5)

	values := decodeValues(t, document)
	require.Equal(t, []string{
		"global", "components", "ingress", "postgres", "gatewayApi", "muster", "kagent", "agent-platform-mcps", "agent-sandbox", "backstage",
	}, mappingKeys(rootMapping(document)), "keep, components, wiring, umbrella keys, then one block per dependency in dependency order")
	require.Empty(t, asMap(t, values["agent-sandbox"]), "a dependency without fleet values gets an empty block")
	require.Equal(t, false, asMap(t, asMap(t, values["backstage"])["ingress"])["enabled"], "the contract fills a dependency block")

	for _, dropped := range []string{"gitops", "agentSandbox", "networkPolicy"} {
		require.NotContains(t, values, dropped)
	}

	global := asMap(t, values["global"])
	require.Equal(t, []string{"registry", "networkPolicy", "domain"}, mappingKeys(mustGet(t, rootMapping(document), "global")),
		"kept keys, then the moved wiring block, then the contract additions")
	netpol := asMap(t, global["networkPolicy"])
	require.Equal(t, false, netpol["enabled"], "the vanilla overlay wins over the moved block")
	require.Equal(t, "kubernetes", netpol["flavor"])
	require.Contains(t, result.Moves, PathMove{From: []string{"networkPolicy"}, To: []string{"global", "networkPolicy"}},
		"the template rewrite follows the relocation")

	require.Equal(t, false, asMap(t, asMap(t, values["gatewayApi"])["gateway"])["create"], "umbrella key from the contract")
	require.Equal(t, "kagent-pg", asMap(t, values["postgres"])["clusterName"], "a wiring block without moveTo stays top-level")

	componentsMap := asMap(t, values["components"])
	require.Equal(t, []string{"muster", "kagent", "agent-platform-mcps", "agent-sandbox", "backstage"},
		mappingKeys(mustGet(t, rootMapping(document), "components")))
	require.Equal(t, true, asMap(t, componentsMap["muster"])["enabled"], "a fleet entry without `enabled` is on")
	require.Equal(t, false, asMap(t, componentsMap["kagent"])["enabled"], "the fleet components.kagent.enabled default")
	require.Equal(t, true, asMap(t, componentsMap["agent-platform-mcps"])["enabled"])
	require.Equal(t, false, asMap(t, componentsMap["agent-sandbox"])["enabled"], "a component with no values block still takes its fleet default")
	require.Equal(t, false, asMap(t, componentsMap["backstage"])["enabled"], "extra dependency default")

	kagentWiring := asMap(t, componentsMap["kagent"])
	require.Contains(t, kagentWiring, "controllerRoute", "lifted wiring key")
	sandboxWiring := asMap(t, componentsMap["agent-sandbox"])
	require.Equal(t, true, asMap(t, sandboxWiring["podSecurity"])["enabled"])

	muster := asMap(t, values["muster"])
	require.Equal(t, true, muster["enabled"], "keepEnabled forwards the key the muster chart owns")
	require.Equal(t, "muster", muster["fullnameOverride"])
	require.Equal(t, 1, muster["replicaCount"], "the vanilla overlay reaches a dependency block")

	kagentBlock := asMap(t, values["kagent"])
	require.Equal(t, []string{"kagent"}, keysOf(kagentBlock), "nested under valuesKey")
	inner := asMap(t, kagentBlock["kagent"])
	require.NotContains(t, inner, "enabled")
	require.NotContains(t, inner, "controllerRoute")
	require.Equal(t, "kagent-controller", asMap(t, inner["controller"])["image"])
	require.Empty(t, asMap(t, inner["controller"])["env"], "the overlay replaces sequences")

	ingress := asMap(t, values["ingress"])
	require.Equal(t, true, ingress["fromConnectivity"], "wiring blocks come from the connectivity values")
}

func TestTransformPreservesCommentsAndSchemaAnnotations(t *testing.T) {
	result, err := Transform(fixtureInputs(t))
	require.NoError(t, err)
	out, err := encodeYAML(result.Document)
	require.NoError(t, err)
	text := string(out)
	require.Contains(t, text, "# route comment survives")
	require.Contains(t, text, "# netpol comment survives the move")
	require.Contains(t, text, "GENERATED by hack/curate.sh from agent-platform 3.0.0")
	require.Contains(t, text, "muster:  # @schema skipProperties: true", "the fleet annotation moves to the chart-name key")
	require.Contains(t, text, "kagent:  "+opaqueBlockAnnotation, "a block without a fleet annotation gets the opaque one")
	require.Contains(t, text, "backstage:  "+opaqueBlockAnnotation+"\n  ingress:", "a filled block is block-style, the annotation moves to the key")
	require.Contains(t, text, "labels: {}  # @schema type: object; additionalProperties: true",
		"an empty contract mapping carries its annotation onto the fleet node")
}

