func TestConfigValidateMoveTo(t *testing.T) {
	var config Config
	require.NoError(t, yaml.Unmarshal([]byte(strings.Replace(fixtureConfig, "ingress: {action: wiring}", "ingress: {action: wiring, moveTo: flat}", 1)), &config))
	require.ErrorContains(t, config.Validate(), "keys.ingress: moveTo \"flat\" must be a dotted path")

	config = Config{}
	require.NoError(t, yaml.Unmarshal([]byte(strings.Replace(fixtureConfig, "global: {action: keep}", "global: {action: keep, moveTo: a.b}", 1)), &config))
	require.ErrorContains(t, config.Validate(), "keys.global: moveTo is only valid with action wiring")
}

func TestTransformOverlay(t *testing.T) {
	t.Run("unknown top-level key", func(t *testing.T) {
		in := fixtureInputs(t)
		in.Overlay = parseDocument(t, fixtureOverlay+"notAnUmbrellaKey: 1\n")
		_, err := Transform(in)
		require.ErrorContains(t, err, `overlay key "notAnUmbrellaKey"`)
	})
	t.Run("unknown components entry", func(t *testing.T) {
		in := fixtureInputs(t)
		in.Overlay = parseDocument(t, fixtureOverlay+"components:\n  nope:\n    enabled: true\n")
		_, err := Transform(in)
		require.ErrorContains(t, err, "overlay components.nope is not a dependency")
	})
	t.Run("applied last", func(t *testing.T) {
		in := fixtureInputs(t)
		in.Overlay = parseDocument(t, fixtureOverlay+"components:\n  kagent:\n    enabled: true\ningress:\n  parentRefs:\n    - name: edge\n")
		result, err := Transform(in)
		require.NoError(t, err)
		values := decodeValues(t, result.Document)
		require.Equal(t, true, asMap(t, asMap(t, values["components"])["kagent"])["enabled"])
		require.Contains(t, asMap(t, asMap(t, values["components"])["kagent"]), "controllerRoute", "overlay merges, it does not replace")
		require.Equal(t, 1, asMap(t, values["muster"])["replicaCount"])
		require.Equal(t, "muster", asMap(t, values["muster"])["fullnameOverride"])
		require.Len(t, asMap(t, values["ingress"])["parentRefs"], 1, "sequences are replaced")
	})
}

func TestGiantswarmExample(t *testing.T) {
	in := fixtureInputs(t)
	result, err := Transform(in)
	require.NoError(t, err)

	example, err := GiantswarmExample(in.Config, result.BeforeOverlay, in.Overlay, parseDocument(t, fixtureGiantswarmInputs))
	require.NoError(t, err)
	values := decodeValues(t, example)

	global := asMap(t, values["global"])
	require.Equal(t, map[string]any{"enabled": true, "flavor": "cilium"}, asMap(t, global["networkPolicy"]), "the fleet default the overlay turned off")
	require.Equal(t, "example.gigantic.io", global["domain"], "inputs win over the reverted leaves")
	require.Equal(t, true, asMap(t, asMap(t, values["gatewayApi"])["gateway"])["create"], "an umbrella key has no fleet value; only the inputs set it")
	require.NotContains(t, values, "muster", "a leaf the fleet does not ship is not reverted")
	require.NotContains(t, values, "backstage", "the contract is not reverted")
	env := asMap(t, asMap(t, asMap(t, values["kagent"])["kagent"])["controller"])["env"]
	require.Len(t, env, 1, "a replaced sequence is restored whole")

	out, err := encodeYAML(example)
	require.NoError(t, err)
	require.Contains(t, string(out), "GENERATED by hack/curate.sh from agent-platform 2.13.0")
}

func keysOf(mapping map[string]any) []string {
	keys := make([]string, 0, len(mapping))
	for key := range mapping {
		keys = append(keys, key)
	}
	return keys
}
