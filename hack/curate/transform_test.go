func TestGiantswarmExample(t *testing.T) {
	in := fixtureInputs(t)
	result, err := Transform(in)
	require.NoError(t, err)

	example, err := GiantswarmExample(in.Config, result.BeforeOverlay, in.Overlay, parseDocument(t, fixtureGiantswarmInputs))
	require.NoError(t, err)
	values := decodeValues(t, example)

	global := asMap(t, values["global"])
	require.Equal(t, map[string]any{"enabled": true, "flavor": "cilium"}, asMap(t, global["networkPolicy"]), "the fleet default the overlay turned off")
	require.Equal(t, "example.gigantic.io", global["domain"], "inputs win over the reverted leaves")
	require.Equal(t, true, asMap(t, asMap(t, values["gatewayApi"])["gateway"])["create"], "an umbrella key comes from the inputs alone")
	require.NotContains(t, values, "muster", "a leaf without a fleet counterpart is not reverted")
	require.NotContains(t, values, "backstage", "the contract is not reverted")
	env := asMap(t, asMap(t, asMap(t, values["kagent"])["kagent"])["controller"])["env"]
	require.Len(t, env, 1, "a replaced sequence is restored whole")

	out, err := encodeYAML(example)
	require.NoError(t, err)
	require.Contains(t, string(out), "GENERATED by hack/curate.sh from agent-platform 3.0.0")
}

